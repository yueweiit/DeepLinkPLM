alter table plm_product add column product_identity_mode varchar(32) not null default 'legacy';
create table plm_product_code_reservation (
    reservation_id bigint generated by default as identity primary key,
    product_id bigint not null references plm_product(product_id),
    specific_code varchar(2) not null check (specific_code ~ '^[A-Z]{2}$'),
    state varchar(24) not null check (state in ('proposed','confirmed','released','invalid_held')),
    pinned_at timestamptz, confirmed_at timestamptz, invalidated_at timestamptz,
    reason text, created_by varchar(128) not null, created_at timestamptz not null default now(),
    updated_by varchar(128) not null, updated_at timestamptz not null default now()
);
create unique index uk_product_code_reservation_occupied on plm_product_code_reservation(specific_code)
    where state in ('proposed','confirmed','invalid_held');
create unique index uk_product_code_reservation_current on plm_product_code_reservation(product_id)
    where state in ('proposed','confirmed','invalid_held');
create index idx_product_code_reservation_product on plm_product_code_reservation(product_id,reservation_id desc);

-- Deleted/archived identities still reserve codes. Unknown ownership never means free.
create view plm_product_identity_evidence as
with recursive roots(product_id,root_id) as (
    select product_id,product_id from plm_product where parent_product_id is null
    union all select p.product_id,r.root_id from plm_product p join roots r on p.parent_product_id=r.product_id
), evidence as (
    select r.root_id owner_id,v.code from plm_product p left join roots r using(product_id)
    cross join lateral (values
        (upper(btrim(p.product_specific_code))),
        (regexp_replace(upper(btrim(p.product_code_prefix)),'^[MN](?=[A-Z]{2}$)','')),
        (substring(upper(p.mold_code_prefix) from '^M([A-Z]{2})')),
        (substring(upper(p.product_code) from '^[MN]([A-Z]{2})[0-9]')),
        (substring(upper(p.finished_product_code) from '^N([A-Z]{2})[0-9]'))
    ) v(code)
    union all select r.root_id,upper(btrim(m.product_specific_code)) from plm_product_mold_code m left join roots r using(product_id)
    union all select r.root_id,substring(upper(m.mold_code) from '^M([A-Z]{2})') from plm_product_mold_code m left join roots r using(product_id)
    union all select a.product_line_id,upper(btrim(s.product_specific_code)) from plm_mold_code_source s
        left join plm_mold_application a on a.external_instance_id=s.approval_instance_id and a.product_line_id=a.project_id
    union all select a.product_line_id,substring(upper(s.mold_code) from '^[MN]([A-Z]{2})') from plm_mold_code_source s
        left join plm_mold_application a on a.external_instance_id=s.approval_instance_id and a.product_line_id=a.project_id
    union all select r.root_id,substring(upper(i.inventory_code) from '^[MN]([A-Z]{2})[0-9]') from plm_inventory i
        left join roots r on r.product_id=nullif(to_jsonb(i)->>'product_id','')::bigint
    union all select a.product_line_id,(regexp_matches(upper(a.generated_codes),'M([A-Z]{2})[0-9]{6}','g'))[1]
        from plm_mold_application a
)
select distinct owner_id,code from evidence where code ~ '^[A-Z]{2}$';

create function plm_guard_reserved_product_code() returns trigger language plpgsql as $$
declare code text;
begin
    if TG_OP='UPDATE' and old.product_identity_mode<>new.product_identity_mode then
        raise exception '产品编码机制不能通过旧入口切换';
    end if;
    if new.product_type='product_line' then
        -- Legacy writers can fill any of these fields. Lock every candidate in one order.
        for code in select distinct v.code from (values
            (upper(btrim(new.product_specific_code))),
            (regexp_replace(upper(btrim(new.product_code_prefix)),'^[MN](?=[A-Z]{2}$)','')),
            (substring(upper(new.mold_code_prefix) from '^M([A-Z]{2})')),
            (substring(upper(new.product_code) from '^[MN]([A-Z]{2})[0-9]')),
            (substring(upper(new.finished_product_code) from '^N([A-Z]{2})[0-9]'))
        ) v(code) where v.code ~ '^[A-Z]{2}$' order by v.code loop
            perform pg_advisory_xact_lock(hashtextextended('product-specific:'||code,0));
            if exists(select 1 from plm_product_code_reservation r where r.specific_code=code
                and r.state in ('proposed','confirmed','invalid_held') and r.product_id<>new.product_id) then
                raise exception '产品编码已被拟定或正式身份占用';
            end if;
        end loop;
    end if;
    return new;
end $$;
create trigger guard_reserved_product_code before insert or update on plm_product
    for each row execute function plm_guard_reserved_product_code();

-- Deferred: reservation, final node, and root identity must commit atomically.
create function plm_check_managed_product_identity() returns trigger language plpgsql as $$
declare p plm_product%rowtype; r plm_product_code_reservation%rowtype;
begin
    select * into p from plm_product where product_id=new.product_id;
    if p.product_identity_mode<>'reserved_v1' then return null; end if;
    select * into r from plm_product_code_reservation where product_id=p.product_id and state='confirmed';
    if r.reservation_id is not null then
        if p.product_specific_code is distinct from r.specific_code
            or p.product_code_prefix is distinct from r.specific_code
            or p.mold_code_prefix is distinct from 'M'||r.specific_code then
            raise exception '正式产品身份与已转正占号不一致';
        end if;
        if not exists(select 1 from plm_product_development_event e where e.product_id=p.product_id
            and e.kind='product_code_confirmed' and e.data->>'nodeKey'='LAUNCH_SHIP') then
            raise exception '产品编码缺少最终发模转正事实';
        end if;
        -- Subsequent revisions may return the timeline, but the first confirmation must be final.
        if TG_TABLE_NAME='plm_product_code_reservation' and (TG_OP='INSERT' or coalesce(to_jsonb(old)->>'state','')<>'confirmed')
            and (p.timeline_current_confirmed is distinct from true or p.timeline_confirmed_node_key is distinct from 'LAUNCH_SHIP') then
            raise exception '产品编码尚未完成最终发模';
        end if;
    elsif nullif(btrim(p.product_specific_code),'') is not null
        or nullif(btrim(p.product_code_prefix),'') is not null or nullif(btrim(p.mold_code_prefix),'') is not null then
        raise exception '拟定产品编码只能在完成最终发模时正式写入';
    end if;
    return null;
end $$;
create constraint trigger check_managed_product_identity after insert or update on plm_product
    deferrable initially deferred for each row execute function plm_check_managed_product_identity();
create constraint trigger check_managed_reservation_identity after insert or update on plm_product_code_reservation
    deferrable initially deferred for each row execute function plm_check_managed_product_identity();

create function plm_keep_confirmed_product_identity() returns trigger language plpgsql as $$
begin
    if old.state='confirmed' and (TG_OP='DELETE' or new.state is distinct from old.state
        or new.product_id is distinct from old.product_id or new.specific_code is distinct from old.specific_code) then
        raise exception '已转正产品编码不可释放或改绑';
    end if;
    if TG_OP='DELETE' then return old; end if;
    return new;
end $$;
create trigger keep_confirmed_product_identity before update or delete on plm_product_code_reservation
    for each row execute function plm_keep_confirmed_product_identity();
